-- 3. Owner-driver linkage (Owner-Operator Mode) — self-link, idempotent,
--    Membership.role never touched.
-- =============================================================================
do $$
declare v_org uuid; v_r1 public.owner_driver_link_result; v_r2 public.owner_driver_link_result;
begin
  select id into v_org from public.organizations where name = 'Onboarding Test Org A';

  set local role authenticated;
  set local request.jwt.claim.sub = '98000000-0000-0000-0000-0000000000a1';
  v_r1 := public.link_self_as_driver(v_org, 'Owner A', '555-0100');
  v_r2 := public.link_self_as_driver(v_org, 'Owner A', '555-0100'); -- re-entry
  reset role;

  if v_r1.linked and v_r1.driver_id is not null then
    raise notice 'TEST OWNERDRIVER-1 (self-link creates a real Driver row): PASS';
  else
    raise notice 'TEST OWNERDRIVER-1 (self-link creates a real Driver row): FAIL';
  end if;

  if not v_r2.linked and v_r2.driver_id = v_r1.driver_id then
    raise notice 'TEST OWNERDRIVER-2 (re-entry is idempotent, no duplicate Driver row): PASS';
  else
    raise notice 'TEST OWNERDRIVER-2 (re-entry is idempotent, no duplicate Driver row): FAIL';
  end if;

  if (select role from public.memberships where organization_id = v_org and user_id = '98000000-0000-0000-0000-0000000000a1') = 'organization_admin' then
    raise notice 'TEST OWNERDRIVER-3 (Membership.role UNCHANGED after self-link): PASS';
  else
    raise notice 'TEST OWNERDRIVER-3 (Membership.role UNCHANGED after self-link): FAIL';
  end if;

  -- Owner-Operator Mode actually works end to end: driver_get_profile
  -- resolves for this org_admin now that current_driver_id no longer
  -- requires role='driver' specifically (P1-E3-S9 relaxation).
  set local role authenticated;
  set local request.jwt.claim.sub = '98000000-0000-0000-0000-0000000000a1';
  declare v_profile public.driver_profile_result;
  begin
    v_profile := public.driver_get_profile(v_org);
    if v_profile.driver_id = v_r1.driver_id then
      raise notice 'TEST OWNERDRIVER-4 (driver_get_profile resolves for a self-linked org_admin): PASS';
    else
      raise notice 'TEST OWNERDRIVER-4 (driver_get_profile resolves for a self-linked org_admin): FAIL';
    end if;
  end;
  reset role;

  -- ZD-100's own property still holds: deactivate the Membership, confirm driver access is denied.
  update public.memberships set status = 'inactive' where organization_id = v_org and user_id = '98000000-0000-0000-0000-0000000000a1';
  set local role authenticated;
  set local request.jwt.claim.sub = '98000000-0000-0000-0000-0000000000a1';
  begin
    perform public.driver_get_profile(v_org);
    raise notice 'TEST OWNERDRIVER-5 (inactive Membership denies driver access, ZD-100 preserved): FAIL (expected denial, got success)';
  exception when sqlstate 'ZW002' then
    raise notice 'TEST OWNERDRIVER-5 (inactive Membership denies driver access, ZD-100 preserved): PASS';
  end;
  reset role;
  update public.memberships set status = 'active' where organization_id = v_org and user_id = '98000000-0000-0000-0000-0000000000a1';
end $$;

