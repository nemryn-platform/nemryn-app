-- =============================================================================
-- 4/5/6. Driver invite — create, duplicate (reused), foreign-org denial
-- =============================================================================
do $$
declare v_org_a uuid; v_org_b uuid; v_r1 public.driver_invite_result; v_r2 public.driver_invite_result;
begin
  select id into v_org_a from public.organizations where name = 'Onboarding Test Org A';
  select id into v_org_b from public.organizations where name = 'Onboarding Test Org B';

  set local role authenticated;
  set local request.jwt.claim.sub = '98000000-0000-0000-0000-0000000000a1'; -- Org A admin
  v_r1 := public.create_driver_invite(v_org_a, 'invited-driver@example.test', 'Invited Driver', '555-0111');
  v_r2 := public.create_driver_invite(v_org_a, 'invited-driver@example.test', 'Invited Driver', '555-0111'); -- duplicate
  reset role;

  if v_r1.reused = false and v_r1.status = 'pending' then
    raise notice 'TEST INVITE-1 (create_driver_invite creates a real pending invite): PASS';
  else
    raise notice 'TEST INVITE-1 (create_driver_invite creates a real pending invite): FAIL';
  end if;

  if v_r2.reused = true and v_r2.token = v_r1.token and v_r2.invite_id = v_r1.invite_id then
    raise notice 'TEST INVITE-2 (duplicate invite is reused, not duplicated — same token/id): PASS';
  else
    raise notice 'TEST INVITE-2 (duplicate invite is reused, not duplicated — same token/id): FAIL';
  end if;
  if (select count(*) from public.driver_invites where organization_id = v_org_a and email = 'invited-driver@example.test') = 1 then
    raise notice 'TEST INVITE-3 (exactly one invite row exists, not two): PASS';
  else
    raise notice 'TEST INVITE-3 (exactly one invite row exists, not two): FAIL';
  end if;

  -- Foreign-org denial: Org B's admin cannot invite into Org A.
  set local role authenticated;
  set local request.jwt.claim.sub = '98000000-0000-0000-0000-0000000000a2'; -- Org B admin
  begin
    perform public.create_driver_invite(v_org_a, 'sneaky@example.test', 'Sneaky', null);
    raise notice 'TEST INVITE-4 (foreign-org admin cannot invite into a different org): FAIL (expected denial, got success)';
  exception when sqlstate 'ZW002' then
    raise notice 'TEST INVITE-4 (foreign-org admin cannot invite into a different org): PASS';
  end;
  reset role;

  -- A Dispatcher (not Organization Admin) cannot invite either — least
  -- privilege, matching create_driver_profile's own restriction.
  insert into public.memberships (organization_id, user_id, role, status) values (v_org_a, '98000000-0000-0000-0000-0000000000a4', 'dispatcher', 'active');
  set local role authenticated;
  set local request.jwt.claim.sub = '98000000-0000-0000-0000-0000000000a4';
  begin
    perform public.create_driver_invite(v_org_a, 'another@example.test', 'Another', null);
    raise notice 'TEST INVITE-5 (Dispatcher cannot invite a driver — Organization Admin only): FAIL (expected denial, got success)';
  exception when sqlstate 'ZW002' then
    raise notice 'TEST INVITE-5 (Dispatcher cannot invite a driver — Organization Admin only): PASS';
  end;
  reset role;
end $$;

-- =============================================================================
-- Invite redemption — wrong email, revoked, idempotent re-redemption
-- =============================================================================
do $$
declare v_org_a uuid; v_token uuid; v_r public.driver_invite_redemption_result; v_r2 public.driver_invite_redemption_result; v_ok boolean := true;
begin
  select id into v_org_a from public.organizations where name = 'Onboarding Test Org A';
  select token into v_token from public.driver_invites where organization_id = v_org_a and email = 'invited-driver@example.test';

  -- Correct person redeems.
  set local role authenticated;
  set local request.jwt.claim.sub = '98000000-0000-0000-0000-0000000000a3'; -- invited-driver@example.test
  v_r := public.redeem_driver_invite(v_token);
  reset role;

  if v_r.driver_linked and v_r.membership_created then
    raise notice 'TEST REDEEM-1 (correct-email redemption creates Membership + Driver): PASS';
  else
    raise notice 'TEST REDEEM-1 (correct-email redemption creates Membership + Driver): FAIL';
  end if;

  if exists (select 1 from public.memberships where organization_id = v_org_a and user_id = '98000000-0000-0000-0000-0000000000a3' and role = 'driver' and status = 'active') then
    raise notice 'TEST REDEEM-2 (invited Driver receives Driver role ONLY): PASS';
  else
    raise notice 'TEST REDEEM-2 (invited Driver receives Driver role ONLY): FAIL';
  end if;

  if (select status from public.driver_invites where token = v_token) = 'accepted' then
    raise notice 'TEST REDEEM-3 (invite marked accepted): PASS';
  else
    raise notice 'TEST REDEEM-3 (invite marked accepted): FAIL';
  end if;

  -- Idempotent re-redemption by the SAME person.
  set local role authenticated;
  set local request.jwt.claim.sub = '98000000-0000-0000-0000-0000000000a3';
  begin
    v_r2 := public.redeem_driver_invite(v_token);
    if v_r2.driver_id <> v_r.driver_id then v_ok := false; end if;
  exception when others then
    v_ok := false;
  end;
  reset role;
  if v_ok then
    raise notice 'TEST REDEEM-4 (repeat redemption by the same already-accepted person is a safe no-op): PASS';
  else
    raise notice 'TEST REDEEM-4 (repeat redemption by the same already-accepted person is a safe no-op): FAIL';
  end if;
end $$;

