do $$
declare v_a public.organization_signup_result; v_b public.organization_signup_result;
begin
  -- P1-PILOT-S4B-R4A: signup_create_organization is internal-only (not
  -- executable by `authenticated`), so it is exercised directly here as the
  -- owner role, with the caller identity set via the same JWT-claim GUC
  -- auth.uid() reads. Its real client-reachable entry points are the
  -- complete_pending_signup* gates, covered from section 13 onward and by
  -- tenant_settings_foundation_tests.sql.
  set local request.jwt.claim.sub = '98000000-0000-0000-0000-0000000000a1';
  v_a := public.signup_create_organization('Onboarding Test Org A', 'Owner A', 'starting', 'America/New_York');

  set local request.jwt.claim.sub = '98000000-0000-0000-0000-0000000000a2';
  v_b := public.signup_create_organization('Onboarding Test Org B', 'Owner B', 'growing', 'America/Chicago');

  if v_a.organization_id is not null and v_b.organization_id is not null and v_a.organization_id <> v_b.organization_id then
    raise notice 'TEST SIGNUP-1 (two signups create two isolated organizations): PASS';
  else
    raise notice 'TEST SIGNUP-1 (two signups create two isolated organizations): FAIL (a=%, b=%)', v_a.organization_id, v_b.organization_id;
  end if;

  if v_a.role = 'organization_admin' and v_b.role = 'organization_admin' then
    raise notice 'TEST SIGNUP-2 (owner Membership created as organization_admin): PASS';
  else
    raise notice 'TEST SIGNUP-2 (owner Membership created as organization_admin): FAIL (a.role=%, b.role=%)', v_a.role, v_b.role;
  end if;

  if exists (select 1 from public.memberships where id = v_a.membership_id and organization_id = v_a.organization_id and status = 'active')
     and exists (select 1 from public.memberships where id = v_b.membership_id and organization_id = v_b.organization_id and status = 'active') then
    raise notice 'TEST SIGNUP-3 (owner Membership row is real, active, org-scoped): PASS';
  else
    raise notice 'TEST SIGNUP-3 (owner Membership row is real, active, org-scoped): FAIL';
  end if;

  if exists (select 1 from public.user_profiles where id = '98000000-0000-0000-0000-0000000000a1' and display_name = 'Owner A') then
    raise notice 'TEST SIGNUP-4 (UserProfile created atomically): PASS';
  else
    raise notice 'TEST SIGNUP-4 (UserProfile created atomically): FAIL';
  end if;

  -- Multi-org safety: Owner A has no membership at all in Org B, and
  -- vice versa — no accidental cross-organization grant.
  if not exists (select 1 from public.memberships where organization_id = v_b.organization_id and user_id = '98000000-0000-0000-0000-0000000000a1')
     and not exists (select 1 from public.memberships where organization_id = v_a.organization_id and user_id = '98000000-0000-0000-0000-0000000000a2') then
    raise notice 'TEST MULTIORG-1 (Owner A has zero access to Org B and vice versa): PASS';
  else
    raise notice 'TEST MULTIORG-1 (Owner A has zero access to Org B and vice versa): FAIL';
  end if;

  -- Owner A cannot read Org B's row at all (RLS, not just app logic).
  set local role authenticated;
  set local request.jwt.claim.sub = '98000000-0000-0000-0000-0000000000a1';
  perform 1 from public.organizations where id = v_b.organization_id;
  if not found then
    raise notice 'TEST MULTIORG-2 (Owner A cannot SELECT Org B via RLS): PASS';
  else
    raise notice 'TEST MULTIORG-2 (Owner A cannot SELECT Org B via RLS): FAIL';
  end if;
  reset role;
end $$;

