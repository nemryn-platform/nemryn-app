      raise notice 'TEST SIGNUPCONT-6 (unauthenticated call rejected): PASS';
    else
      raise notice 'TEST SIGNUPCONT-6 (unauthenticated call rejected): FAIL (unexpected sqlstate %)', sqlstate;
    end if;
  end;
end $$;

