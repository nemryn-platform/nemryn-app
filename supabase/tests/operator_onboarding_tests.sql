  -- PASSENGER-1/2 above just deactivated (create_trip correctly
  -- requires status='active', so reusing it would test the wrong thing).
  set local role authenticated;
  set local request.jwt.claim.sub = '98000000-0000-0000-0000-0000000000a1';
  insert into public.passengers (organization_id, display_name) values (v_org_a, 'Onboarding First-Trip Passenger') returning id into v_passenger_id;
  v_trip := public.create_trip(v_org_a, v_passenger_id, 'Onboarding first-trip pickup', 'Onboarding first-trip destination');
  reset role;

  if v_trip.created and v_trip.state = 'scheduled' and v_trip.organization_id = v_org_a then
    raise notice 'TEST FIRSTTRIP-1 (a brand-new organization creates its own first Trip): PASS';
  else
    raise notice 'TEST FIRSTTRIP-1 (a brand-new organization creates its own first Trip): FAIL';
  end if;
